# ============================================================
# SECTION 1: IMPORTS
# Import Python and SQLAlchemy components.
# ============================================================

from datetime import datetime, timezone

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    func,
    text,
)

from sqlalchemy.orm import (
    DeclarativeBase,
    Mapped,
    mapped_column,
)


# ============================================================
# SECTION 2: DATABASE BASE CLASS
# All BMDA database models share this Base class.
# ============================================================

class Base(DeclarativeBase):
    pass


# ============================================================
# SECTION 3: USER MODEL
# Stores information about BMDA system users.
# ============================================================

class User(Base):

    __tablename__ = "users"

    # ========================================================
    # SECTION 4: DATABASE CONSTRAINTS AND INDEXES
    # These rules already exist in PostgreSQL.
    # Define them here to keep the Python model consistent.
    # ========================================================

    __table_args__ = (

        # RULE 1:
        # Only the four approved BMDA user roles are allowed.
        CheckConstraint(
            "role IN ("
            "'admin', "
            "'assistant_engineer', "
            "'supervisor', "
            "'field_user'"
            ")",
            name="ck_users_valid_role",
        ),

        # RULE 2:
        # Admin must not have an assigned management unit.
        # Other roles must have a management unit.
        CheckConstraint(
            "("
            "role = 'admin' AND upazila_id IS NULL"
            ") OR ("
            "role IN ("
            "'assistant_engineer', "
            "'supervisor', "
            "'field_user'"
            ") AND upazila_id IS NOT NULL"
            ")",
            name="ck_users_upazila_assignment",
        ),

        # RULE 3:
        # Only one Assistant Engineer per management unit.
        # This partial unique index already exists.
        Index(
            "ux_users_one_assistant_per_upazila",
            "upazila_id",
            unique=True,
            postgresql_where=text(
                "role = 'assistant_engineer'"
            ),
        ),

        # RULE 4:
        # Prevent usernames differing only by letter case.
        #
        # Example:
        # xen_admin, XEN_ADMIN and Xen_Admin are duplicates.
        #
        # This unique index already exists in PostgreSQL.
        Index(
            "ux_users_username_lower",
            func.lower(text("username")),
            unique=True,
        ),
    )

    # ========================================================
    # SECTION 5: USER ID
    # Unique numeric ID generated by PostgreSQL.
    # ========================================================

    id: Mapped[int] = mapped_column(
        Integer,
        primary_key=True,
        index=True,
    )

    # ========================================================
    # SECTION 6: USER IDENTITY
    # Full name and unique username.
    # ========================================================

    full_name: Mapped[str] = mapped_column(
        String(150),
        nullable=False,
    )

    username: Mapped[str] = mapped_column(
        String(100),
        unique=True,
        nullable=False,
        index=True,
    )

    # ========================================================
    # SECTION 7: PASSWORD SECURITY
    # Store only the password hash.
    # Never store a plain password.
    # ========================================================

    password_hash: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
    )

    # ========================================================
    # SECTION 8: USER ROLE
    # One of the four approved BMDA roles.
    # ========================================================

    role: Mapped[str] = mapped_column(
        String(30),
        nullable=False,
    )

    # ========================================================
    # SECTION 9: MANAGEMENT UNIT ASSIGNMENT
    # Admin has no assigned unit.
    # Other roles must belong to a management unit.
    # ========================================================

    upazila_id: Mapped[int | None] = mapped_column(
        ForeignKey("upazilas.id"),
        nullable=True,
    )

    # ========================================================
    # SECTION 10: REPORTING SUPERVISOR
    # Stores the ID of the user's direct supervisor.
    # Hierarchy validation is handled separately.
    # ========================================================

    supervisor_id: Mapped[int | None] = mapped_column(
        ForeignKey("users.id"),
        nullable=True,
    )

    # ========================================================
    # SECTION 11: ACCOUNT STATUS
    # New accounts are active by default.
    # ========================================================

    is_active: Mapped[bool] = mapped_column(
        Boolean,
        default=True,
        nullable=False,
    )

    # ========================================================
    # SECTION 12: ACCOUNT CREATION TIME
    # Automatically record creation time in UTC.
    # ========================================================

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )